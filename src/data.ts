/** كل قطع الأسبوع مع تعريفاتها (تُستخدم في الشاشة التفصيلية) */
export function allWeekHymns(): (DayHymn & { dayLabel: string; setId: string })[] {
  const out: (DayHymn & { dayLabel: string; setId: string })[] = []
  for (const d of [...adamHosu.days, ...watsHosu.days]) {
    for (const h of d.hymns) out.push({ ...h, dayLabel: d.day, setId: d.id.startsWith('adam') ? 'adam' : 'wats' })
  }
  return out
}

export function findHymn(id: string): (DayHymn & { dayLabel: string; setId: string }) | undefined {
  return allWeekHymns().find((h) => h.id === id)
}

